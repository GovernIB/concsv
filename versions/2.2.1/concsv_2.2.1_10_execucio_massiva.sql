-- ConCSV 2.2.1: execucions massives (accions que s'executen en segon pla).
-- Equivalents a IPA_EXECUCIO_MASSIVA i IPA_MASSIVA_CONTINGUT de RIPEA, amb els camps que es fan servir.

CREATE TABLE CSV_EXECUCIO_MASSIVA
(
  ID                    NUMBER(19)          NOT NULL,
  TIPUS                 VARCHAR2(64 CHAR)   NOT NULL,
  DATA_INICI            TIMESTAMP(6),
  DATA_FI               TIMESTAMP(6),
  ENVIAR_CORREU         NUMBER(1)           DEFAULT 0 NOT NULL,
  ESTAT                 VARCHAR2(20 CHAR)   NOT NULL,
  CANCELACIO_DATA       TIMESTAMP(6),
  CANCELACIO_USUARI     VARCHAR2(64 CHAR),
  NODE                  VARCHAR2(255 CHAR),
  DATA_HEARTBEAT        TIMESTAMP(6),
  CREATEDBY_CODI        VARCHAR2(64 CHAR)   NOT NULL,
  CREATEDDATE           TIMESTAMP(6)        NOT NULL,
  LASTMODIFIEDBY_CODI   VARCHAR2(64 CHAR),
  LASTMODIFIEDDATE      TIMESTAMP(6)
);

COMMENT ON COLUMN CSV_EXECUCIO_MASSIVA.TIPUS IS 'ACTUALITZAR_DADES_DOCUMENTS_EXCLOSOS';
COMMENT ON COLUMN CSV_EXECUCIO_MASSIVA.DATA_INICI IS 'A partir d''aquesta data el proces en segon pla la pot agafar';
COMMENT ON COLUMN CSV_EXECUCIO_MASSIVA.DATA_FI IS 'Data de finalitzacio; NULL mentre no ha acabat';
COMMENT ON COLUMN CSV_EXECUCIO_MASSIVA.ENVIAR_CORREU IS 'Si s''ha d''avisar per correu l''usuari que l''ha creada quan acabi';
COMMENT ON COLUMN CSV_EXECUCIO_MASSIVA.ESTAT IS 'PENDENT, EN_CURS, FINALITZADA o CANCELADA';
COMMENT ON COLUMN CSV_EXECUCIO_MASSIVA.CANCELACIO_DATA IS 'Data en que es va demanar la cancelacio';
COMMENT ON COLUMN CSV_EXECUCIO_MASSIVA.CANCELACIO_USUARI IS 'Usuari que va demanar la cancelacio';
COMMENT ON COLUMN CSV_EXECUCIO_MASSIVA.NODE IS 'Node del servidor que l''esta processant';
COMMENT ON COLUMN CSV_EXECUCIO_MASSIVA.DATA_HEARTBEAT IS 'Darrer senyal de vida del node que l''esta processant';

ALTER TABLE CSV_EXECUCIO_MASSIVA ADD (
  CONSTRAINT CSV_EXECUCIO_MASSIVA_PK PRIMARY KEY (ID));

CREATE INDEX CSV_EXECUCIO_MASSIVA_ESTAT_I ON CSV_EXECUCIO_MASSIVA (ESTAT, DATA_FI);
CREATE INDEX CSV_EXECUCIO_MASSIVA_CREAT_I ON CSV_EXECUCIO_MASSIVA (CREATEDDATE);

CREATE TABLE CSV_MASSIVA_CONTINGUT
(
  ID                    NUMBER(19)          NOT NULL,
  EXECUCIO_MASSIVA_ID   NUMBER(19)          NOT NULL,
  DATA_INICI            TIMESTAMP(6),
  DATA_FI               TIMESTAMP(6),
  ESTAT                 VARCHAR2(20 CHAR)   NOT NULL,
  ERROR                 VARCHAR2(2000 CHAR),
  ORDRE                 NUMBER(10)          NOT NULL,
  ELEMENT_TIPUS         VARCHAR2(32 CHAR)   NOT NULL,
  ELEMENT_ID            NUMBER(19)          NOT NULL,
  ELEMENT_NOM           VARCHAR2(256 CHAR),
  CREATEDBY_CODI        VARCHAR2(64 CHAR)   NOT NULL,
  CREATEDDATE           TIMESTAMP(6)        NOT NULL,
  LASTMODIFIEDBY_CODI   VARCHAR2(64 CHAR),
  LASTMODIFIEDDATE      TIMESTAMP(6)
);

COMMENT ON COLUMN CSV_MASSIVA_CONTINGUT.ESTAT IS 'PENDENT, FINALITZAT, ERROR o CANCELAT';
COMMENT ON COLUMN CSV_MASSIVA_CONTINGUT.ELEMENT_TIPUS IS 'DOCUMENT (document exclos)';
COMMENT ON COLUMN CSV_MASSIVA_CONTINGUT.ELEMENT_ID IS 'Identificador de l''element a tractar';
COMMENT ON COLUMN CSV_MASSIVA_CONTINGUT.ELEMENT_NOM IS 'Nom de l''element en crear l''execucio (UUID o CSV del document)';

ALTER TABLE CSV_MASSIVA_CONTINGUT ADD (
  CONSTRAINT CSV_MASSIVA_CONTINGUT_PK PRIMARY KEY (ID));

ALTER TABLE CSV_MASSIVA_CONTINGUT ADD (
  CONSTRAINT CSV_MASSIVA_CONT_EXEC_FK FOREIGN KEY (EXECUCIO_MASSIVA_ID)
    REFERENCES CSV_EXECUCIO_MASSIVA (ID));

CREATE INDEX CSV_MASSIVA_CONT_EXEC_I ON CSV_MASSIVA_CONTINGUT (EXECUCIO_MASSIVA_ID, ESTAT);
CREATE INDEX CSV_MASSIVA_CONT_ELEM_I ON CSV_MASSIVA_CONTINGUT (ELEMENT_TIPUS, ELEMENT_ID);

GRANT SELECT, UPDATE, INSERT, DELETE ON CSV_EXECUCIO_MASSIVA TO WWW_CONCSV;
GRANT SELECT, UPDATE, INSERT, DELETE ON CSV_MASSIVA_CONTINGUT TO WWW_CONCSV;
