-- 01_create_table
CREATE TABLE CSV_ENTITAT
(
  ID                    NUMBER(19)          NOT NULL,
  CODI                  VARCHAR2(64 CHAR)   NOT NULL,
  NOM                   VARCHAR2(256 CHAR)  NOT NULL,
  DESCRIPCIO            VARCHAR2(1024 CHAR),
  CIF                   VARCHAR2(9 CHAR)    NOT NULL,
  CODI_DIR3             VARCHAR2(9 CHAR)    NOT NULL,
  COLOR_FONS            VARCHAR2(32 CHAR),
  COLOR_LLETRA          VARCHAR2(32 CHAR),
  LOGO_CAP              BLOB,
  COLOR_FONS_DARK       VARCHAR2(32 CHAR),
  COLOR_LLETRA_DARK     VARCHAR2(32 CHAR),
  LOGO_CAP_DARK         BLOB,
  ACTIVA                NUMBER(1)           DEFAULT 1 NOT NULL,
  FECHA_ACTUALIZACION   TIMESTAMP(6),
  FECHA_SINCRONIZACION  TIMESTAMP(6),
  VERSION               NUMBER(19)          NOT NULL,
  CREATEDBY_CODI        VARCHAR2(64 CHAR)   NOT NULL,
  CREATEDDATE           TIMESTAMP(6)        NOT NULL,
  LASTMODIFIEDBY_CODI   VARCHAR2(64 CHAR),
  LASTMODIFIEDDATE      TIMESTAMP(6)
);

CREATE TABLE CSV_USUARI
(
  CODI                  VARCHAR2(64 CHAR)   NOT NULL,
  NOM                   VARCHAR2(200 CHAR),
  NIF                   VARCHAR2(9 CHAR),
  EMAIL                 VARCHAR2(200 CHAR),
  IDIOMA                VARCHAR2(2 CHAR)    DEFAULT 'CA' NOT NULL,
  ENTITAT_ACTUAL_ID     NUMBER(19),
  NUM_ELEMENTS_PAGINA   NUMBER(19),
  ROL_ACTUAL            VARCHAR2(64 CHAR),
  TEMA_APLICACIO        VARCHAR2(16 CHAR),
  ESTIL_MENU            VARCHAR2(16 CHAR)   DEFAULT 'TEMA' NOT NULL,
  VERSION               NUMBER(19)          NOT NULL,
  DARRER_PERIODE		TIMESTAMP(6),
  DARRERA_ACTIVITAT		TIMESTAMP(6)
);

CREATE TABLE CSV_AVIS
(
  ID                    NUMBER(19)          NOT NULL,
  ASSUMPTE              VARCHAR2(256 CHAR)  NOT NULL,
  MISSATGE              VARCHAR2(2048 CHAR) NOT NULL,
  DATA_INICI            DATE                NOT NULL,
  DATA_FINAL            DATE,
  ACTIU                 NUMBER(1)           NOT NULL,
  AVIS_NIVELL           VARCHAR2(10 CHAR)   NOT NULL,
  ENTITAT_ID            NUMBER(19),
  CREATEDBY_CODI        VARCHAR2(64 CHAR)   NOT NULL,
  CREATEDDATE           TIMESTAMP(6)        NOT NULL,
  LASTMODIFIEDBY_CODI   VARCHAR2(64 CHAR),
  LASTMODIFIEDDATE      TIMESTAMP(6)
);

CREATE TABLE CSV_CONFIG_TYPE
(
  CODE                  VARCHAR2(128 CHAR)  NOT NULL,
  VALUE                 VARCHAR2(2048 CHAR)
);

CREATE TABLE CSV_CONFIG_GROUP
(
  CODE                  VARCHAR2(128 CHAR)  NOT NULL,
  PARENT_CODE           VARCHAR2(128 CHAR),
  POSITION              NUMBER(10)          DEFAULT 0 NOT NULL,
  DESCRIPTION           VARCHAR2(512 CHAR)
);

CREATE TABLE CSV_CONFIG
(
  KEY                   VARCHAR2(256 CHAR)  NOT NULL,
  VALUE                 VARCHAR2(2048 CHAR),
  DESCRIPTION           VARCHAR2(2048 CHAR),
  GROUP_CODE            VARCHAR2(128 CHAR)  NOT NULL,
  TYPE_CODE             VARCHAR2(128 CHAR)  NOT NULL,
  POSITION              NUMBER(10)          DEFAULT 0 NOT NULL,
  JBOSS_PROPERTY        NUMBER(1)           DEFAULT 0 NOT NULL,
  LASTMODIFIEDBY_CODI   VARCHAR2(64 CHAR),
  LASTMODIFIEDDATE      TIMESTAMP(6)
);

CREATE TABLE CSV_DOCUMENT_EXCLOS
(
  ID                    NUMBER(19)          NOT NULL,
  VALOR                 VARCHAR2(256 CHAR)  NOT NULL,
  CREATEDBY_CODI        VARCHAR2(64 CHAR)   NOT NULL,
  CREATEDDATE           TIMESTAMP(6)        NOT NULL,
  LASTMODIFIEDBY_CODI   VARCHAR2(64 CHAR),
  LASTMODIFIEDDATE      TIMESTAMP(6)
);

CREATE TABLE CSV_INTEGRACIO_ACCIO
(
  ID                    NUMBER(19)          NOT NULL,
  DATA                  TIMESTAMP(6)        NOT NULL,
  INTEGRACIO_CODI       VARCHAR2(64 CHAR)   NOT NULL,
  DESCRIPCIO            VARCHAR2(1024 CHAR),
  ENDPOINT              VARCHAR2(1024 CHAR),
  PARAMETRES            CLOB,
  TIPUS                 VARCHAR2(32 CHAR),
  TEMPS_RESPOSTA        NUMBER(19),
  ESTAT                 VARCHAR2(16 CHAR)   NOT NULL,
  ENTITAT_CODI          VARCHAR2(64 CHAR),
  ERROR_DESCRIPCIO      VARCHAR2(2000 CHAR),
  EXCEPCIO_MESSAGE      VARCHAR2(2000 CHAR),
  EXCEPCIO_STACKTRACE   CLOB,
  CREATEDBY_CODI        VARCHAR2(64 CHAR)   NOT NULL,
  CREATEDDATE           TIMESTAMP(6)        NOT NULL,
  LASTMODIFIEDBY_CODI   VARCHAR2(64 CHAR),
  LASTMODIFIEDDATE      TIMESTAMP(6)
);

COMMENT ON COLUMN CSV_INTEGRACIO_ACCIO.INTEGRACIO_CODI IS 'ARXIU, CUSTODIA, VALIDACIO_FIRMES o CONVERSIO';
COMMENT ON COLUMN CSV_INTEGRACIO_ACCIO.PARAMETRES IS 'JSON amb els parametres de la peticio (p. ex. hash o uuid)';
COMMENT ON COLUMN CSV_INTEGRACIO_ACCIO.TEMPS_RESPOSTA IS 'Temps de resposta en ms';
COMMENT ON COLUMN CSV_INTEGRACIO_ACCIO.ESTAT IS 'OK o ERROR';

-- 01 index
CREATE INDEX CSV_AVIS_ENTITAT_FK_I ON CSV_AVIS (ENTITAT_ID);
CREATE INDEX CSV_AVIS_DATA_INICI_I ON CSV_AVIS (DATA_INICI);
CREATE INDEX CSV_AVIS_DATA_FINAL_I ON CSV_AVIS (DATA_FINAL);

CREATE UNIQUE INDEX CSV_DOCUMENT_EXCLOS_VALOR_IDX ON CSV_DOCUMENT_EXCLOS (VALOR);

CREATE INDEX CSV_CONFIG_GROUP_PARENT_FK_I ON CSV_CONFIG_GROUP (PARENT_CODE);
CREATE INDEX CSV_CONFIG_GROUP_FK_I ON CSV_CONFIG (GROUP_CODE);
CREATE INDEX CSV_CONFIG_TYPE_FK_I ON CSV_CONFIG (TYPE_CODE);

CREATE INDEX CSV_INTEGRACIO_ACCIO_DATA_I ON CSV_INTEGRACIO_ACCIO (DATA);
CREATE INDEX CSV_INTEGRACIO_ACCIO_CODI_I ON CSV_INTEGRACIO_ACCIO (INTEGRACIO_CODI, DATA);

