  CONSTRAINT CSV_ENTITAT_DIR3_UK UNIQUE (CODI_DIR3));

ALTER TABLE CSV_USUARI ADD (
  CONSTRAINT CSV_USUARI_PK PRIMARY KEY (CODI));

